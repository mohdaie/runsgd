import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {readFileSync} from 'node:fs';
const roads=createRequire(import.meta.url)('../assets/singapore-road-alerts.js');
const a={lat:1.3,lon:103.8},b={lat:1.31,lon:103.8};
const g={id:'erp',number:'1',lines:[[[103.7999,1.305],[103.8001,1.305]]]};
const cache={points:[a,b],cum:[0,1105.4]};
const hits=roads.crossings(cache,[g]);
assert.equal(hits.length,1);assert.ok(Math.abs(hits[0].progress-552.7)<.01);
assert.equal(roads.crossings({points:[{...a,lon:103.8003},{...b,lon:103.8003}],cum:cache.cum},[g]).length,0,'parallel carriageway must not trigger');
assert.equal(roads.crossings(cache,[g,{...g,id:'paired'}]).length,1,'paired frames with the same number collapse');
const loop=roads.crossings({points:[a,b,a],cum:[0,1105.4,2210.8]},[g]);
assert.equal(loop.length,2,'return journey retains its own crossing');
assert.equal(roads.intersection(a,b,a,b),null,'parallel spans do not cross');
const now=100000,fix={mode:'DRIVE',inSingapore:true,progress:200,offRoute:3,accuracy:8,timestamp:now,acceptedTimestamp:now,acceptedAt:now,speed:10,heading:0,routeHeading:0};
assert.ok(roads.nextWarning(hits,fix,now));
for(const overrides of [{mode:'WALK'},{mode:'BUS'},{inSingapore:false},{error:true},{accuracy:31},{accuracy:null},{offRoute:31},{progress:null},{timestamp:now-6501,acceptedTimestamp:now-6501},{timestamp:now+1001,acceptedTimestamp:now+1001},{acceptedAt:now-6501},{acceptedTimestamp:now-1000},{heading:180},{progress:553}])assert.equal(roads.nextWarning(hits,{...fix,...overrides},now),null,JSON.stringify(overrides));
assert.ok(roads.nextWarning(hits,{...fix,mode:'TWO_WHEELER'},now));
assert.ok(roads.nextWarning(hits,{...fix,heading:90,routeHeading:90},now),'bend before the ERP uses current road direction');
const tracker=roads.tracker();
assert.equal(tracker.update(hits,fix,now),null);
assert.equal(tracker.update(hits,fix,now),null,'UI ticks do not count as new GPS fixes');
assert.equal(tracker.update(hits,{...fix,timestamp:now-1,acceptedTimestamp:now-1},now),null,'older fix cannot confirm');
assert.ok(tracker.update(hits,{...fix,timestamp:now+1000,acceptedTimestamp:now+1000},now+1000));
assert.equal(tracker.update(hits,{...fix,progress:580,timestamp:now+2000,acceptedTimestamp:now+2000},now+2000),null);
assert.equal(tracker.update(hits,{...fix,progress:500,timestamp:now+3000,acceptedTimestamp:now+3000},now+3000),null,'GPS jitter does not repeat a passed warning');
tracker.reset();assert.equal(tracker.update(hits,fix,now),null,'new route resets confirmation');
assert.ok(tracker.update(hits,{...fix,timestamp:now+1000,acceptedTimestamp:now+1000},now+1000));
assert.equal(tracker.update(hits,{...fix,accuracy:80},now+1000),null,'weak GPS immediately clears');
const data=JSON.parse(readFileSync(new URL('../assets/singapore-erp.json',import.meta.url)));
assert.equal(data.gantries.length,101);assert.equal(data.published,'2026-09');
for(const gantry of data.gantries)for(const line of gantry.lines)for(const [lon,lat] of line){assert.ok(lon>103.6&&lon<104.1);assert.ok(lat>1.2&&lat<1.5);}
console.log('Singapore ERP tests passed: exact spans, wrong carriageways, paired frames, return routes, GPS trust, heading, two-fix confirmation and passed-gantry suppression.');
